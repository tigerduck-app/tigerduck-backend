"""Builds the Grafana dashboards in monitoring/grafana/dashboards/.

The JSON files there are generated by this script and are not edited by
hand: a filter, colour or query shared by many panels is defined once here.
To change a dashboard, edit this file and run it (no dependencies beyond
Python 3):

    python3 monitoring/grafana/build_dashboards.py

Grafana picks the new JSON up within 30 seconds. A panel tried out in the
UI has to be ported back into this script, or the next run overwrites it.
"""
