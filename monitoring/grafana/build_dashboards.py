def var_sql(name, label, query, multi=True, include_all=True, all_value=None, hide=0):
    v = {"name": name, "label": label, "type": "query", "datasource": PG, "query": query.strip(),
         "definition": query.strip(), "multi": multi, "includeAll": include_all, "refresh": 2,
         "sort": 1, "hide": hide, "current": {"selected": True, "text": ["All"], "value": ["$__all"]},
         "options": []}
    if all_value:
        v["allValue"] = all_value
    return v


