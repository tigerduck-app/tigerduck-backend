# ----------------------------------------------------------------- colours
GREEN, RED, ORANGE, YELLOW, BLUE, GRAY, PURPLE = (
    "green", "red", "orange", "yellow", "blue", "#8e8e8e", "purple")
STATUS_COLORS = {
    # good
    "sent": GREEN, "succeeded": GREEN, "processed": GREEN, "active": GREEN, "success": GREEN,
    "online": GREEN, "info": GREEN, "2xx": GREEN,
    # bad
    "failed": RED, "error": RED, "invalid": RED, "critical": PURPLE, "5xx": RED,
    # in between
    "partial_failed": ORANGE, "warn": ORANGE, "4xx": ORANGE, "missed": ORANGE, "skipped": YELLOW,
    "running": YELLOW, "processing": YELLOW, "pending": BLUE, "debug": BLUE, "3xx": BLUE,
    # inert
    "cancelled": GRAY, "disabled": GRAY, "unknown": GRAY, "inactive": GRAY,
}


def color_overrides(regex=False):
    """Fixed colours for status-named series so 'failed' is never green."""
    out = []
    for name, color in STATUS_COLORS.items():
        matcher = ({"id": "byRegexp", "options": f"(.* )?{name}"} if regex
                   else {"id": "byName", "options": name})
        out.append({"matcher": matcher,
                    "properties": [{"id": "color", "value": {"mode": "fixed", "fixedColor": color}}]})
    return out


def steps(*pairs, base="green"):
    out = [{"color": base, "value": None}]
    for color, value in pairs:
        out.append({"color": color, "value": value})
    return {"mode": "absolute", "steps": out}


# ----------------------------------------------------------------- targets
def prom(expr, legend="", instant=False, ref="A", table=False):
    t = {"refId": ref, "datasource": PROM, "expr": expr, "legendFormat": legend or "__auto",
         "range": not instant}
    if instant:
        t["instant"] = True
    if table:
        t["format"] = "table"
    return t


def sql(raw, fmt="table", ref="A"):
    return {"refId": ref, "datasource": PG, "rawSql": raw.strip(), "format": fmt,
            "rawQuery": True, "editorMode": "code"}


def loki(expr, legend="", instant=False, ref="A"):
    return {"refId": ref, "datasource": LOKI, "expr": expr, "legendFormat": legend,
            "queryType": "instant" if instant else "range", "editorMode": "code"}


# ----------------------------------------------------------------- layout
class Layout:
    def __init__(self):
        self.panels, self.y, self.x, self.row_h, self.next_id = [], 0, 0, 0, 1

    def _place(self, w, h):
        if self.x + w > 24:
            self.y += self.row_h
            self.x, self.row_h = 0, 0
        pos = {"x": self.x, "y": self.y, "w": w, "h": h}
        self.x += w
        self.row_h = max(self.row_h, h)
        return pos

    def row(self, title, collapsed=False):
        if self.x:
            self.y += self.row_h
        self.x, self.row_h = 0, 0
        self.panels.append({"id": self.next_id, "type": "row", "title": title, "collapsed": collapsed,
                            "gridPos": {"x": 0, "y": self.y, "w": 24, "h": 1}, "panels": []})
        self.next_id += 1
        self.y += 1

    def reserve(self):
        pid = self.next_id
        self.next_id += 1
        return pid

    def add(self, panel, w, h, pid=None):
        if pid is None:
            pid = self.reserve()
        panel["id"] = pid
        panel["gridPos"] = self._place(w, h)
        self.panels.append(panel)


