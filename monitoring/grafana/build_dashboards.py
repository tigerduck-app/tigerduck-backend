def taipei_day(col):
    """`col`'s day in Taiwan time. $__timeGroup('1d') floors to UTC
    midnight, which would cut every day at 08:00 local time."""
    return f"date_trunc('day', {col}, 'Asia/Taipei')"


def per_day(counts, by_metric):
    """A daily bar chart's query, from `counts`: a SELECT of `day` (made
    with taipei_day), `value` and, when by_metric, `metric`. Every day in
    the range gets a row, at 0 when nothing happened: Grafana sizes bars by
    the closest two points, so a missing day would stretch its neighbours
    across it."""
    days = f"""days AS (
    SELECT generate_series({taipei_day("$__timeFrom()::timestamptz")}, $__timeTo()::timestamptz, interval '1 day') AS day
)"""
    if not by_metric:
        return f"""WITH {days},
counts AS (
{counts.strip()}
)
SELECT d.day AS "time", COALESCE(c.value, 0) AS value
FROM days d
LEFT JOIN counts c ON c.day = d.day
ORDER BY 1"""
    return f"""WITH {days},
counts AS (
{counts.strip()}
),
metrics AS (SELECT DISTINCT metric FROM counts)
SELECT d.day AS "time", m.metric, COALESCE(c.value, 0) AS value
FROM days d
CROSS JOIN metrics m
LEFT JOIN counts c ON c.day = d.day AND c.metric = m.metric
ORDER BY 1"""


