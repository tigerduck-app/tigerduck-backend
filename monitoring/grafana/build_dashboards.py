DASH_DS = {"type": "datasource", "uid": "-- Dashboard --"}
PLATFORM_COLORS = {"iPhone \\+ iPad": "blue", "macOS": "purple", "Android": "green"}
PLATFORM_GROUP = """CASE WHEN {col} IN ('ios', 'ipados') THEN '{a}'
                WHEN {col} = 'macos' THEN '{b}'
                WHEN {col} = 'android' THEN '{c}'
                ELSE 'other' END"""


def stretches(name):
    """Merges each key's activity into active stretches: every moment of
    activity keeps the key active for 14 days, and overlapping 14-day spans
    join up, so at any time a key sits inside at most one stretch and
    counting stretches counts keys. {name}_daily has one row per key per day
    with that day's first and last moment, so the edges stay exact."""
    return f"""{name}_marked AS (
    SELECT key, day, first_at, last_at,
           CASE WHEN lag(last_at) OVER w + interval '14 days' >= first_at THEN 0 ELSE 1 END AS starts_new
    FROM {name}_daily
    WINDOW w AS (PARTITION BY key ORDER BY day)
),
{name}_numbered AS (
    SELECT key, first_at, last_at, sum(starts_new) OVER (PARTITION BY key ORDER BY day) AS stretch
    FROM {name}_marked
),
{name}_spans AS (
    SELECT key, min(first_at) AS active_from, max(last_at) + interval '14 days' AS active_until
    FROM {name}_numbered
    GROUP BY key, stretch
)"""


# One query feeds the whole top of the dashboard (both graphs and every big
# number), so auth_sessions is scanned once per refresh rather than once per
# panel. Every other panel there reads its result through the Dashboard
# datasource.
USERBASE_SQL = f"""WITH points AS (
    -- Sample times across the range, plus now() so the last point is the
    -- current number.
    SELECT generate_series(
               date_trunc('hour', $__timeFrom()::timestamptz),
               now(),
               GREATEST(make_interval(secs => $__interval_ms / 1000.0), interval '1 hour')
           ) AS t
    UNION
    SELECT now()
),
seen AS (
    -- Activity: logins and access-token refreshes (auth_sessions keeps every
    -- one, and an app in use refreshes every 15 minutes), plus each
    -- device's latest request.
    SELECT device_id, created_at AS at
    FROM auth_sessions
    WHERE device_id IS NOT NULL
      AND created_at > $__timeFrom()::timestamptz - interval '14 days'
    UNION ALL
    SELECT id, last_seen_at
    FROM user_devices
    WHERE last_seen_at > $__timeFrom()::timestamptz - interval '14 days'
),
dev AS (
    SELECT d.id, d.created_at, d.deleted_at, u.student_id,
           {PLATFORM_GROUP.format(col="d.platform", a="iphone_ipad", b="macos", c="android")} AS grp
    FROM user_devices d
    JOIN users u ON u.id = d.user_id
),
device_daily AS (
    SELECT device_id AS key, date_trunc('day', at) AS day, min(at) AS first_at, max(at) AS last_at
    FROM seen
    GROUP BY 1, 2
),
student_daily AS (
    SELECT dv.student_id AS key, dd.day, min(dd.first_at) AS first_at, max(dd.last_at) AS last_at
    FROM device_daily dd
    JOIN dev dv ON dv.id = dd.key
    WHERE dv.student_id IS NOT NULL
    GROUP BY 1, 2
),
{stretches("device")},
{stretches("student")}
SELECT p.t AS "time", usr.*, reg.*, act.*,
       usr."Active users, 14 days"::float / NULLIF(usr."Registered users", 0) AS "Active share"
FROM points p
CROSS JOIN LATERAL (
    SELECT (SELECT count(DISTINCT u.student_id)
            FROM users u
            WHERE u.student_id IS NOT NULL
              AND u.created_at <= p.t
              AND (u.deleted_at IS NULL OR u.deleted_at > p.t)) AS "Registered users",
           (SELECT count(*)
            FROM student_spans s
            WHERE s.active_from <= p.t AND s.active_until > p.t
              -- Counted like "Registered users": not before the account
              -- existed, nor after it was deleted.
              AND EXISTS (SELECT 1
                          FROM users u
                          WHERE u.student_id = s.key
                            AND u.created_at <= p.t
                            AND (u.deleted_at IS NULL OR u.deleted_at > p.t))) AS "Active users, 14 days"
) AS usr
CROSS JOIN LATERAL (
    SELECT count(*) FILTER (WHERE grp = 'iphone_ipad') AS "Registered: iPhone + iPad",
           count(*) FILTER (WHERE grp = 'macos') AS "Registered: macOS",
           count(*) FILTER (WHERE grp = 'android') AS "Registered: Android",
           count(*) AS "Registered: all"
    FROM dev
    WHERE created_at <= p.t AND (deleted_at IS NULL OR deleted_at > p.t)
) AS reg
CROSS JOIN LATERAL (
    SELECT count(*) FILTER (WHERE dv.grp = 'iphone_ipad') AS "Active 14d: iPhone + iPad",
           count(*) FILTER (WHERE dv.grp = 'macos') AS "Active 14d: macOS",
           count(*) FILTER (WHERE dv.grp = 'android') AS "Active 14d: Android",
           count(*) AS "Active 14d: all"
    FROM device_spans s
    JOIN dev dv ON dv.id = s.key
    WHERE s.active_from <= p.t AND s.active_until > p.t
      -- A deleted device stops counting as active, as it stops counting
      -- as registered.
      AND (dv.deleted_at IS NULL OR dv.deleted_at > p.t)
) AS act
ORDER BY 1"""


def from_panel(title, panel_id, field, color, desc="", unit="short", decimals=None):
    """A big number taken from another panel's query: its latest value."""
    p = stat(title, DASH_DS, [{"refId": "A", "datasource": DASH_DS, "panelId": panel_id, "withTransforms": False}],
             thresholds=steps(base=color), desc=desc, graph=True, unit=unit, decimals=decimals)
    p["options"]["reduceOptions"]["fields"] = f"/^{field}$/"
    return p


def without_fields(pattern):
    """Drops the fields matching `pattern`. Excluding rather than including
    keeps the time field, whatever name Grafana gives it."""
    return [{"id": "filterFieldsByName", "options": {"exclude": {"pattern": pattern}}}]


def line_styles(colors):
    out = []
    for name, color in colors.items():
        out.append({"matcher": {"id": "byRegexp", "options": f".*{name}$"},
                    "properties": [{"id": "color", "value": {"mode": "fixed", "fixedColor": color}}]})
    out.append({"matcher": {"id": "byRegexp", "options": "^Active.*"},
                "properties": [{"id": "custom.lineStyle", "value": {"fill": "dash", "dash": [10, 10]}},
                               {"id": "custom.fillOpacity", "value": 0}]})
    out.append({"matcher": {"id": "byRegexp", "options": ".*: all$"},
                "properties": [{"id": "custom.hideFrom", "value": {"viz": True, "legend": True, "tooltip": False}}]})
    return out


def wide_graph(panel):
    panel["fieldConfig"]["defaults"]["custom"]["lineWidth"] = 2
    panel["options"]["legend"].update({"calcs": ["lastNotNull"], "displayMode": "table", "placement": "right"})
    return panel


ACTIVE_DESC = ("A device is active for 14 days after any login, token refresh or request. Apps in use refresh "
               "their token every 15 minutes, and every refresh is kept, so the history reaches back to launch.")

L = Layout()
L.row("Users")
source = L.reserve()  # the Users graph, which runs USERBASE_SQL
L.add(from_panel("Registered users", source, "Registered users", "blue",
                 desc="Distinct student IDs signed in at least once, not deleted."), 6, 5)
L.add(from_panel("Active users, 14 days", source, "Active users, 14 days", "green",
                 desc="Students with at least one device active in the last 14 days. " + ACTIVE_DESC), 6, 5)
L.add(stat("New users in range", PG, [sql("""
SELECT count(DISTINCT student_id) AS "new"
FROM users
WHERE student_id IS NOT NULL AND deleted_at IS NULL AND $__timeFilter(created_at)
""")], thresholds=steps(base="blue"), desc="Students whose first sign-in falls in the selected time range."), 6, 5)
L.add(from_panel("Active share", source, "Active share", "green", unit="percentunit", decimals=0,
                 desc="Active users over registered users, both as in the Users graph below."), 6, 5)
users_panel = wide_graph(series("Users", PG, [sql(USERBASE_SQL, fmt="time_series")], decimals=0,
                                desc="Registered: distinct student IDs. Active (dashed): students with a device active in the trailing 14 days. " + ACTIVE_DESC))
users_panel["fieldConfig"]["overrides"] = [
    {"matcher": {"id": "byName", "options": "Registered users"},
     "properties": [{"id": "color", "value": {"mode": "fixed", "fixedColor": "blue"}}]},
    {"matcher": {"id": "byName", "options": "Active users, 14 days"},
     "properties": [{"id": "color", "value": {"mode": "fixed", "fixedColor": "green"}},
                    {"id": "custom.lineStyle", "value": {"fill": "dash", "dash": [10, 10]}},
                    {"id": "custom.fillOpacity", "value": 0}]},
]
users_panel["maxDataPoints"] = 200
users_panel["transformations"] = without_fields("^((Registered|Active 14d): .*|Active share)$")
L.add(users_panel, 24, 10, pid=source)

L.row("Devices")
for group, color in (("iPhone \\+ iPad", "blue"), ("macOS", "purple"), ("Android", "green"), ("all", "text")):
    L.add(from_panel(f"Registered: {group.replace(chr(92), '')}", source, f"Registered: {group}", color,
                     desc="Registered devices, not deleted."), 6, 4)
for group, color in (("iPhone \\+ iPad", "blue"), ("macOS", "purple"), ("Android", "green"), ("all", "text")):
    L.add(from_panel(f"Active 14d: {group.replace(chr(92), '')}", source, f"Active 14d: {group}", color,
                     desc="Devices active in the last 14 days. " + ACTIVE_DESC), 6, 4)
devices_panel = wide_graph(series(
    "Devices", DASH_DS, [{"refId": "A", "datasource": DASH_DS, "panelId": source, "withTransforms": False}],
    decimals=0,
    desc="Solid: registered devices. Dashed: devices active in the trailing 14 days. Same colour, same platform. Hover for the totals. " + ACTIVE_DESC))
devices_panel["fieldConfig"]["overrides"] = line_styles(PLATFORM_COLORS)
devices_panel["fieldConfig"]["defaults"]["custom"]["fillOpacity"] = 0
devices_panel["transformations"] = without_fields("^(Registered users|Active users, 14 days|Active share)$")
L.add(devices_panel, 24, 12)

L.row("Growth")
new_users = series("New users per day", PG, [sql(per_day(f"""
SELECT {taipei_day("created_at")} AS day, count(DISTINCT student_id) AS value
FROM users
WHERE student_id IS NOT NULL AND $__timeFilter(created_at)
GROUP BY 1
""", by_metric=False), fmt="time_series")], bars=True, decimals=0)
new_users["fieldConfig"]["defaults"]["displayName"] = "new users"
L.add(new_users, 12, 8)
new_devices = series("New devices per day", PG, [sql(per_day(f"""
SELECT {taipei_day("created_at")} AS day,
       {PLATFORM_GROUP.format(col="platform", a="iPhone + iPad", b="macOS", c="Android")} AS metric,
       count(*) AS value
FROM user_devices
WHERE $__timeFilter(created_at)
GROUP BY 1, 2
""", by_metric=True), fmt="time_series")], bars=True, stacked=True, decimals=0)
new_devices["fieldConfig"]["overrides"] = [
    {"matcher": {"id": "byName", "options": n},
     "properties": [{"id": "color", "value": {"mode": "fixed", "fixedColor": c}}]}
    for n, c in (("iPhone + iPad", "blue"), ("macOS", "purple"), ("Android", "green"), ("other", GRAY))]
L.add(new_devices, 12, 8)

dashboards["userbase"] = dashboard(
    "tigerduck-userbase", "Userbase",
    "Registered and active users and devices over time. Rebuilt from the database, so the history reaches back to launch.",
    L.panels, "now-90d", refresh="5m")

# ----------------------------------------------------------------- write
for name, d in dashboards.items():
    (OUT / f"{name}.json").write_text(json.dumps(d, indent=2, ensure_ascii=False) + "\n")
    print(f"{name}.json: {sum(1 for p in d['panels'] if p['type'] != 'row')} panels, "
          f"{len(d['templating']['list'])} variables")
