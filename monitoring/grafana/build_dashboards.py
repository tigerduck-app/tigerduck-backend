def stat(title, ds, targets, unit="short", thresholds=None, desc="", mappings=None, graph=False,
         text_mode="auto", decimals=None, color_mode="value"):
    defaults = {"unit": unit, "color": {"mode": "thresholds"},
                "thresholds": thresholds or steps(), "mappings": mappings or []}
    if decimals is not None:
        defaults["decimals"] = decimals
    return {"type": "stat", "title": title, "description": desc, "datasource": ds, "targets": targets,
            "fieldConfig": {"defaults": defaults, "overrides": []},
            "options": {"reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": False},
                        "colorMode": color_mode, "graphMode": "area" if graph else "none",
                        "justifyMode": "auto", "textMode": text_mode, "orientation": "auto",
                        "wideLayout": True, "showPercentChange": False}}


def series(title, ds, targets, unit="short", desc="", stacked=False, bars=False, min0=True,
           percent=False, colors=False, regex_colors=False, legend_table=False, decimals=None):
    custom = {"drawStyle": "bars" if bars else "line", "lineWidth": 1,
              "fillOpacity": 70 if bars else 12, "showPoints": "never", "spanNulls": False,
              "barAlignment": 0,
              "stacking": {"mode": "percent" if percent else ("normal" if stacked else "none"), "group": "A"}}
    defaults = {"unit": "percentunit" if percent else unit, "color": {"mode": "palette-classic"},
                "custom": custom}
    if decimals is not None:
        defaults["decimals"] = decimals
    if min0:
        defaults["min"] = 0
    overrides = color_overrides(regex=regex_colors) if (colors or regex_colors) else []
    legend = ({"displayMode": "table", "placement": "right", "showLegend": True,
               "calcs": ["lastNotNull", "max"]} if legend_table else
              {"displayMode": "list", "placement": "bottom", "showLegend": True})
    return {"type": "timeseries", "title": title, "description": desc, "datasource": ds,
            "targets": targets, "fieldConfig": {"defaults": defaults, "overrides": overrides},
            "options": {"legend": legend, "tooltip": {"mode": "multi", "sort": "desc"}}}


def table(title, ds, targets, desc="", units=None, sort=None, colored=None, bools=False,
          from_now=None, widths=None, links=None):
    """colored: column names whose cell text is coloured by STATUS_COLORS."""
    overrides = []
    for name, unit in (units or {}).items():
        overrides.append({"matcher": {"id": "byName", "options": name},
                          "properties": [{"id": "unit", "value": unit}]})
    for name in (from_now or []):
        overrides.append({"matcher": {"id": "byName", "options": name},
                          "properties": [{"id": "unit", "value": "dateTimeFromNow"}]})
    for name in (colored or []):
        overrides.append({"matcher": {"id": "byName", "options": name},
                          "properties": [
                              {"id": "custom.cellOptions", "value": {"type": "color-text"}},
                              {"id": "mappings", "value": [{"type": "value", "options": {
                                  k: {"color": v, "index": i} for i, (k, v) in enumerate(STATUS_COLORS.items())}}]}]})
    if bools:
        overrides.append({"matcher": {"id": "byType", "options": "boolean"},
                          "properties": [
                              {"id": "custom.cellOptions", "value": {"type": "color-text"}},
                              {"id": "custom.align", "value": "center"},
                              {"id": "mappings", "value": [{"type": "value", "options": {
                                  "true": {"text": "on", "color": GREEN, "index": 0},
                                  "false": {"text": "off", "color": GRAY, "index": 1}}}]}]})
    for name, width in (widths or {}).items():
        overrides.append({"matcher": {"id": "byName", "options": name},
                          "properties": [{"id": "custom.width", "value": width}]})
    for name, link in (links or {}).items():
        overrides.append({"matcher": {"id": "byName", "options": name},
                          "properties": [{"id": "links", "value": [link]}]})
    opts = {"showHeader": True, "cellHeight": "sm", "footer": {"show": False}}
    if sort:
        opts["sortBy"] = [{"displayName": sort[0], "desc": sort[1]}]
    return {"type": "table", "title": title, "description": desc, "datasource": ds, "targets": targets,
            "fieldConfig": {"defaults": {"custom": {"align": "auto", "filterable": True,
                                                    "cellOptions": {"type": "auto"}}},
                            "overrides": overrides},
            "options": opts}


def pie(title, ds, targets, desc="", colors=False):
    return {"type": "piechart", "title": title, "description": desc, "datasource": ds, "targets": targets,
            "fieldConfig": {"defaults": {"unit": "short", "color": {"mode": "palette-classic"}},
                            "overrides": color_overrides() if colors else []},
            "options": {"pieType": "donut",
                        "reduceOptions": {"values": True, "calcs": ["lastNotNull"], "fields": ""},
                        "legend": {"displayMode": "table", "placement": "right", "showLegend": True,
                                   "values": ["value", "percent"]},
                        "tooltip": {"mode": "single", "sort": "none"}}}


def bargauge(title, ds, targets, unit="short", desc="", values=False, thresholds=None):
    fc = {"unit": unit, "min": 0}
    if thresholds:
        fc.update({"color": {"mode": "thresholds"}, "thresholds": thresholds})
    else:
        fc["color"] = {"mode": "continuous-BlPu"}
    return {"type": "bargauge", "title": title, "description": desc, "datasource": ds, "targets": targets,
            "fieldConfig": {"defaults": fc, "overrides": []},
            "options": {"orientation": "horizontal", "displayMode": "basic", "showUnfilled": True,
                        "valueMode": "color", "namePlacement": "left", "sizing": "manual",
                        "minVizHeight": 16, "maxVizHeight": 24, "minVizWidth": 8,
                        "text": {"titleSize": 12, "valueSize": 14},
                        "reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": values}}}


def logs(title, expr, desc=""):
    return {"type": "logs", "title": title, "description": desc, "datasource": LOKI,
            "targets": [loki(expr)],
            "options": {"showTime": True, "showLabels": False, "showCommonLabels": False,
                        "wrapLogMessage": True, "prettifyLogMessage": False, "enableLogDetails": True,
                        "enableInfiniteScrolling": True, "dedupStrategy": "none",
                        "sortOrder": "Descending"}}


